const TRANSLATIONS: Record<LangCode, Dict> = { EN, NO, ES, DE, FR, AR };

interface LanguageContextValue {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  lang: 'EN',
  setLang: () => undefined,
  t: (key) => EN[key] ?? key,
});

function applyDocumentLang(code: LangCode) {
  if (typeof document === 'undefined') return;
  const meta = LANGUAGES.find((l) => l.code === code);
  document.documentElement.lang = code.toLowerCase();
  document.documentElement.dir = meta?.dir ?? 'ltr';
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LangCode>('EN');

  useEffect(() => {
    const saved = localStorage.getItem('visor-lang') as LangCode | null;
    if (saved && saved in TRANSLATIONS) {
      setLangState(saved);
      applyDocumentLang(saved);
    } else {
      applyDocumentLang('EN');
    }
  }, []);

  const setLang = useCallback((code: LangCode) => {
    setLangState(code);
    try {
      localStorage.setItem('visor-lang', code);
    } catch {
      /* ignore */
    }
    applyDocumentLang(code);
  }, []);

  const t = useCallback(
    (key: string) => TRANSLATIONS[lang][key] ?? EN[key] ?? key,
    [lang],
  );

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
